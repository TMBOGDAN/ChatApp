-- Schema derived from the SQL queries in server.js.
-- Local demo only: server.js currently stores passwords as plaintext.
CREATE TABLE account (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL
);

CREATE TABLE friendships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id BIGINT NOT NULL REFERENCES account(id),
  receiver_id BIGINT NOT NULL REFERENCES account(id),
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  user1accepted BOOLEAN NOT NULL DEFAULT false,
  user2accepted BOOLEAN NOT NULL DEFAULT false,
  CONSTRAINT different_accounts CHECK (requester_id <> receiver_id)
);

CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_user TEXT NOT NULL,
  receiver_user TEXT NOT NULL,
  content TEXT NOT NULL,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX messages_conversation_idx ON messages (sender_user, receiver_user, sent_at);
CREATE INDEX friendships_receiver_status_idx ON friendships (receiver_id, status);
